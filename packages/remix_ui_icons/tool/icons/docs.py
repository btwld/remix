"""Render MIGRATION.md and the generated blocks of README.md and CHANGELOG.md.

README.md and CHANGELOG.md are maintained by hand; only the text between
their `<!-- generated:... -->` markers comes from the manifest, so counts and
tables cannot drift from the code.
"""

from __future__ import annotations

import re

from manifest import LegacyIcon, Manifest

LUCIDE_DOCS = "https://lucide.dev/icons/"


class DocsError(Exception):
    """A hand-maintained document lost its generated-block markers."""


def _kebab(name: str) -> str:
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"-\1", name).lower()


def _lucide(icon: LegacyIcon) -> str:
    if icon.lucide is None:
        return "—"
    return f"[`LucideIcons.{icon.lucide}`]({LUCIDE_DOCS}{_kebab(icon.lucide)})"


def _escape(text: str) -> str:
    return text.replace("|", "\\|")


def counts(manifest: Manifest) -> dict[str, int]:
    legacy = manifest.legacy
    exact = [icon for icon in legacy if icon.status == "exact"]
    return {
        "glyphs": len(manifest.glyphs),
        "concepts": len(manifest.concepts),
        "legacy": len(legacy),
        "exact": len(exact),
        "kept": len(exact) - len(manifest.deprecated_aliases),
        "aliases": len(manifest.deprecated_aliases),
        "partial": sum(icon.status == "partial" for icon in legacy),
        "removed": sum(icon.status == "removed" for icon in legacy),
        "noLucide": sum(icon.lucide is None for icon in legacy),
    }


def coverage_table(manifest: Manifest) -> str:
    rows = [
        "| Family | Class | Concepts | Glyphs |",
        "| --- | --- | ---: | ---: |",
    ]
    for family in manifest.families:
        concepts = sum(family.key in concept.families for concept in manifest.concepts)
        rows.append(
            f"| {family.label} | `{family.class_name}` | {concepts} | "
            f"{len(manifest.glyphs_of(family))} |"
        )
    rows.append(f"| **Total** | | | **{len(manifest.glyphs)}** |")
    return "\n".join(rows)


def alias_table(manifest: Manifest) -> str:
    rows = ["| 0.1.x name | Use instead |", "| --- | --- |"]
    for alias in manifest.deprecated_aliases:
        rows.append(f"| `RemixIcons.{alias.name}` | `RemixIcons.{alias.target}` |")
    return "\n".join(rows)


def migration(manifest: Manifest) -> str:
    c = counts(manifest)
    first = manifest.reserved[0]
    legacy = sorted(manifest.legacy, key=lambda icon: icon.name)
    kept = [
        icon
        for icon in legacy
        if icon.status == "exact" and icon not in manifest.deprecated_aliases
    ]
    partial = [icon for icon in legacy if icon.status == "partial"]
    removed = [icon for icon in legacy if icon.status == "removed"]

    out = [
        "<!-- GENERATED by tool/icons/generate.py from tool/icons/manifest.yaml. -->",
        "<!-- Do not edit by hand. -->",
        "",
        "# Migrating from remix_ui_icons 0.1.x",
        "",
        "remix_ui_icons 1.0 replaces the 318 Radix Icons 1.3.2 glyphs of 0.1.x with",
        f"the Vector UI pack: {c['concepts']} concepts, {c['glyphs']} glyphs. The font family is",
        f"still `{manifest.font_family}`, but every glyph is new and every codepoint",
        f"moved: 1.0 starts at `0x{manifest.start_codepoint:04X}`, and the 0.1.x range",
        f"`0x{first.first:04X}`–`0x{first.last:04X}` is reserved and never reused, so a",
        "stale codepoint renders nothing rather than the wrong icon.",
        "",
        "Every 0.1.x name falls into one of three groups:",
        "",
        "| Group | Names | What happens in 1.0 |",
        "| --- | ---: | --- |",
        f"| Same name | {c['kept']} | The name is unchanged and renders the new drawing. |",
        f"| Renamed | {c['aliases']} | A `@Deprecated` alias on `RemixIcons` renders the new drawing until 2.0.0. |",
        f"| Partial match | {c['partial']} | Removed. A Remix concept covers part of the meaning; review it before switching. |",
        f"| No match | {c['removed']} | Removed. Use the suggested Lucide icon or your own artwork. |",
        "",
        "The Lucide suggestions name constants in",
        "[`lucide_flutter`](https://pub.dev/packages/lucide_flutter) 1.47. Add it with",
        "`flutter pub add lucide_flutter` and import",
        "`package:lucide_flutter/lucide_flutter.dart`. A suggestion is the closest",
        "drawing, not an exact one; check each in context.",
        "",
        f"{c['noLucide']} names are brand marks with no Lucide equivalent, because Lucide ships",
        "no brand logos. Use the brand's own asset.",
        "",
        "## Renamed",
        "",
        "These still compile, with a deprecation warning that names the",
        "replacement. Rename them before 2.0.0.",
        "",
        alias_table(manifest),
        "",
        "## Same name",
        "",
        "No code change. Each renders the Vector UI drawing of the concept.",
        "",
        ", ".join(f"`{icon.name}`" for icon in kept) + ".",
        "",
        "## Partial matches",
        "",
        "Removed in 1.0. The Remix concept is a starting point, not a drop-in:",
        "the note says what it does not cover.",
        "",
        "| 0.1.x name | Closest Remix icon | What differs | Lucide |",
        "| --- | --- | --- | --- |",
    ]
    for icon in partial:
        out.append(
            f"| `{icon.name}` | `RemixIcons.{icon.target}` | {_escape(icon.note or '')} | "
            f"{_lucide(icon)} |"
        )
    out += [
        "",
        "## No match",
        "",
        "Removed in 1.0, with no Vector UI concept.",
        "",
        "| 0.1.x name | Lucide | Note |",
        "| --- | --- | --- |",
    ]
    for icon in removed:
        out.append(f"| `{icon.name}` | {_lucide(icon)} | {_escape(icon.note or '')} |")
    out += [
        "",
        "## Remix registry presets",
        "",
        "The Vanilla, Fortal, and HeroUI presets have native coverage for every",
        "registry icon in both families. Select `remix` for Outline or `rounded`",
        "for Rounded; either installs `remix_ui_icons`. Projects on the `lucide`",
        "icon library are unaffected.",
        "",
    ]
    return "\n".join(out)


def changelog_block(manifest: Manifest) -> str:
    c = counts(manifest)
    return "\n".join(
        [
            f"- {c['glyphs']} glyphs: {c['concepts']} concepts in "
            + ", ".join(
                f"{family.label} ({sum(family.key in concept.families for concept in manifest.concepts)})"
                for family in manifest.families
            )
            + ", each in outline and filled styles at native 24, 16, and 12 px masters.",
            f"- Of the {c['legacy']} 0.1.x names, {c['kept']} are unchanged, {c['aliases']} are "
            "deprecated aliases until 2.0.0, and "
            f"{c['partial'] + c['removed']} are removed ({c['partial']} partial matches, "
            f"{c['removed']} with no match). [MIGRATION.md](MIGRATION.md) lists every name "
            "with its replacement or closest Lucide icon.",
        ]
    )


def replace_block(document: str, name: str, content: str) -> str:
    begin = f"<!-- generated:{name}:begin -->"
    end = f"<!-- generated:{name}:end -->"
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    if len(pattern.findall(document)) != 1:
        raise DocsError(f"Expected exactly one {begin} ... {end} block")
    return pattern.sub(lambda _: f"{begin}\n{content}\n{end}", document)
